//! Binds the harness to the Juniper App sources it is built from.
//!
//! * Copies named items verbatim out of `src-tauri/src/providers.rs` and
//!   `src-tauri/src/behavior.rs` into `$OUT_DIR/app_extracted.rs`. The harness
//!   compiles those exact bytes against small shim types with the App's field
//!   names, so its gate, grant, preview, denial and neutralization logic is the
//!   App's code, not a re-implementation. A renamed or re-typed item fails the
//!   build instead of silently diverging.
//! * Converts the App's `builtinTools` array (`src/lib/defaults.ts`) to JSON in
//!   `$OUT_DIR/catalog.json`, so the tool catalog is the App's own.
//! * Records the App commit, the git blob IDs of the bound sources at that
//!   commit and in the working tree, and the compiler version.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

const PROVIDER_ITEMS: &[&str] = &[
    "pub(crate) fn offered_tools(",
    "enum ToolGate<'a>",
    "fn requires_per_call_approval(",
    "fn tool_gate<'a>(",
    "fn bounded_preview(",
    "fn permission_preview(",
    "fn denied(",
    "fn permission_grant_allows(",
    "fn memory_belongs_to_assistant(",
];
const BEHAVIOR_ITEMS: &[&str] = &[
    "pub fn neutralize_control_tokens(",
    "fn strip_tags(",
    "pub fn attachments_text(",
    "pub fn attachments_message(",
];
const BOUND_SOURCES: &[&str] = &[
    "src-tauri/src/tools.rs",
    "src-tauri/src/providers.rs",
    "src-tauri/src/behavior.rs",
    "src/lib/defaults.ts",
];

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let root = manifest.join("../..").canonicalize().unwrap();
    let out = PathBuf::from(env::var("OUT_DIR").unwrap());
    for rel in BOUND_SOURCES {
        println!("cargo:rerun-if-changed={}", root.join(rel).display());
    }

    let mut extracted = String::from(
        "// Generated by build.rs: items copied verbatim from the Juniper App sources.\n",
    );
    for (rel, items) in [
        ("src-tauri/src/providers.rs", PROVIDER_ITEMS),
        ("src-tauri/src/behavior.rs", BEHAVIOR_ITEMS),
    ] {
        let source = fs::read_to_string(root.join(rel)).unwrap();
        for item in items {
            extracted.push_str(&format!("\n// from {rel}: {item}\n"));
            extracted.push_str(&extract_item(&source, item).unwrap_or_else(|error| {
                panic!("{rel}: cannot extract `{item}`: {error}");
            }));
            extracted.push('\n');
        }
    }
    fs::write(out.join("app_extracted.rs"), extracted).unwrap();

    let defaults = fs::read_to_string(root.join("src/lib/defaults.ts")).unwrap();
    let catalog = builtin_tools_json(&defaults).expect("src/lib/defaults.ts: builtinTools");
    fs::write(out.join("catalog.json"), catalog).unwrap();

    let git = |args: &[&str]| -> String {
        Command::new("git")
            .arg("-C")
            .arg(&root)
            .args(args)
            .output()
            .ok()
            .filter(|output| output.status.success())
            .map(|output| String::from_utf8_lossy(&output.stdout).trim().to_owned())
            .unwrap_or_default()
    };
    let commit = git(&["rev-parse", "HEAD"]);
    let mut blobs = Vec::new();
    for rel in BOUND_SOURCES {
        let at_commit = git(&["rev-parse", &format!("HEAD:{rel}")]);
        let in_tree = git(&["hash-object", rel]);
        blobs.push(format!("{rel}={at_commit}:{in_tree}"));
    }
    for name in ["HEAD", "index"] {
        let path = git(&["rev-parse", "--git-path", name]);
        if !path.is_empty() {
            let path = Path::new(&path);
            let path = if path.is_absolute() {
                path.to_path_buf()
            } else {
                root.join(path)
            };
            println!("cargo:rerun-if-changed={}", path.display());
        }
    }
    let rustc = env::var("RUSTC").unwrap_or_else(|_| "rustc".into());
    let rustc_version = Command::new(rustc)
        .arg("-V")
        .output()
        .map(|output| String::from_utf8_lossy(&output.stdout).trim().to_owned())
        .unwrap_or_default();
    println!("cargo:rustc-env=JUNIPER_APP_COMMIT={commit}");
    println!("cargo:rustc-env=JUNIPER_APP_BLOBS={}", blobs.join(";"));
    println!("cargo:rustc-env=JUNIPER_RUSTC_VERSION={rustc_version}");
    println!(
        "cargo:rustc-env=JUNIPER_BUILD_PROFILE={}",
        env::var("PROFILE").unwrap_or_default()
    );
}

/// The item whose first line starts (at column 0) with `prefix`, through its
/// matching closing brace. Exactly one such line must exist.
fn extract_item(source: &str, prefix: &str) -> Result<String, String> {
    let starts: Vec<usize> = source
        .match_indices(prefix)
        .map(|(index, _)| index)
        .filter(|index| *index == 0 || source.as_bytes()[index - 1] == b'\n')
        .collect();
    let [start] = starts[..] else {
        return Err(format!("{} definitions found", starts.len()));
    };
    let bytes = source.as_bytes();
    let mut index = start;
    let mut depth = 0usize;
    let mut opened = false;
    while index < bytes.len() {
        match bytes[index] {
            b'/' if bytes.get(index + 1) == Some(&b'/') => {
                while index < bytes.len() && bytes[index] != b'\n' {
                    index += 1;
                }
                continue;
            }
            b'"' => {
                index += 1;
                while index < bytes.len() && bytes[index] != b'"' {
                    index += if bytes[index] == b'\\' { 2 } else { 1 };
                }
            }
            b'\'' => {
                // A char literal ('x', '\n', '{'); otherwise a lifetime ('a).
                if bytes.get(index + 1) == Some(&b'\\') {
                    index += 2;
                    while index < bytes.len() && bytes[index] != b'\'' {
                        index += 1;
                    }
                } else if bytes.get(index + 2) == Some(&b'\'') {
                    index += 2;
                } else if let Some(width) = source[index + 1..].chars().next().map(char::len_utf8)
                    && bytes.get(index + 1 + width) == Some(&b'\'')
                {
                    index += 1 + width;
                }
            }
            b'{' => {
                depth += 1;
                opened = true;
            }
            b'}' => {
                depth = depth.checked_sub(1).ok_or("unbalanced braces")?;
                if opened && depth == 0 {
                    return Ok(source[start..=index].to_owned());
                }
            }
            _ => {}
        }
        index += 1;
    }
    Err("no closing brace".into())
}

/// `export const builtinTools: ToolDefinition[] = [ ... ]` as JSON: single-quoted
/// strings become JSON strings, bare keys are quoted and trailing commas dropped.
fn builtin_tools_json(source: &str) -> Result<String, String> {
    let marker = "export const builtinTools: ToolDefinition[] = ";
    let start = source.find(marker).ok_or("marker not found")? + marker.len();
    let text = &source[start..];
    let chars: Vec<char> = text.chars().collect();
    let mut out = String::new();
    let mut depth = 0i32;
    let mut index = 0;
    while index < chars.len() {
        let c = chars[index];
        match c {
            '\'' => {
                out.push('"');
                index += 1;
                while chars.get(index) != Some(&'\'') {
                    let ch = *chars.get(index).ok_or("unterminated string")?;
                    match ch {
                        '\\' => {
                            let next = *chars.get(index + 1).ok_or("bad escape")?;
                            if next == '\'' {
                                out.push('\'');
                            } else {
                                out.push('\\');
                                out.push(next);
                            }
                            index += 2;
                            continue;
                        }
                        '"' => out.push_str("\\\""),
                        _ => out.push(ch),
                    }
                    index += 1;
                }
                out.push('"');
            }
            '[' | '{' => {
                depth += 1;
                out.push(c);
            }
            ']' | '}' => {
                while out.ends_with(|ch: char| ch.is_whitespace()) {
                    out.pop();
                }
                if out.ends_with(',') {
                    out.pop();
                }
                out.push(c);
                depth -= 1;
                if depth == 0 {
                    return Ok(out);
                }
            }
            c if c.is_ascii_alphabetic() || c == '_' => {
                let begin = index;
                while chars
                    .get(index)
                    .is_some_and(|ch| ch.is_ascii_alphanumeric() || *ch == '_')
                {
                    index += 1;
                }
                let word: String = chars[begin..index].iter().collect();
                let mut look = index;
                while chars.get(look).is_some_and(|ch| ch.is_whitespace()) {
                    look += 1;
                }
                if chars.get(look) == Some(&':') {
                    out.push_str(&format!("\"{word}\""));
                } else if matches!(word.as_str(), "true" | "false" | "null") {
                    out.push_str(&word);
                } else {
                    return Err(format!("unsupported identifier {word}"));
                }
                continue;
            }
            _ => out.push(c),
        }
        index += 1;
    }
    Err("unterminated array".into())
}
